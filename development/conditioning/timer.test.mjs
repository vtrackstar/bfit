import { phases, interval, swim, success } from './engine.mjs';
import { emptyState, observed, actualTotals } from './workflow.mjs';
import { makeCycle, scheduledVisit } from './calendar.mjs';
import { beginTicket, makeTimer, timerPhase, timerStart, timerTick, timerPause, timerHidden, timerAdvance, timerExtend, timerEnd, timerResult, saveTicket, saveTimer, saveManual } from './timer.mjs';

function timerTests(){
 const out=[];const check=(n,b)=>{if(!b)throw Error(n);out.push(n)};const fails=f=>{try{f();return false}catch{return true}};
 const c=makeCycle(100,[0,3]),s=emptyState(100),p={mode:"bike",goal:"B",setup:"bike1",restricted:false,vigorousSuitable:true,existingHard:false,recovery:"normal",comfortableMinutes:5},id=c.slots[0].id;
 const issued=beginTicket(c,s,[],p,id,100,1800,"t1"),ticket=issued.ticket;
 const f={confirmed:true,effort:3,quality:true,warning:false,pain:false};
 let t=makeTimer(ticket);
 check("ticket from calendar",ticket.dose.minutes===5&&ticket.slotId===id);
 check("no future ticket",beginTicket(c,s,[],p,c.slots[1].id,100,1800,"later").ticket===null);
 check("timer starts ready",t.state==="ready");
 check("advance before completion rejected",fails(()=>timerAdvance(t)));
 t=timerStart(t,0);t=timerTick(t,1000);t=timerPause(t,2000);
 check("pause records observed time",t.elapsedMs===2000&&t.state==="paused");
 check("paused clock adds no time",timerTick(t,9000).elapsedMs===2000);
 t=timerStart(t,10000);t=timerTick(t,11000);t=timerHidden(t);
 check("visibility interruption preserves known time",t.elapsedMs===3000&&t.state==="interrupted"&&t.interrupted);
 t=timerStart(t,20000);t=timerTick(t,25000);
 check("long gap credits zero",t.elapsedMs===3000&&t.state==="interrupted");
 t=timerStart(t,30000);t=timerTick(t,29999);
 check("backwards clock safe",t.elapsedMs===3000&&t.state==="interrupted");
 let clock=40000;
 const finishPhase=x=>{let y=timerStart(x,clock);while(y.state==="running"){clock+=1000;y=timerTick(y,clock);}return y;};
 const complete=x=>{let y=x;while(y.state!=="finished"){y=finishPhase(y);y=timerAdvance(y);}return y;};
 let full=complete(makeTimer(ticket));
 check("all phases exact",JSON.stringify(full.actual)===JSON.stringify(phases(ticket.dose)));
 check("no unconfirmed save",fails(()=>saveTimer(c,s,[],full,{...f,confirmed:false},100)));
 let saved=saveTimer(c,s,[],full,f,100);
 check("full actual totals",actualTotals(saved.logs[0]).total===900&&actualTotals(saved.logs[0]).work===300);
 check("save locks original prescription",saved.logs[0].dose.minutes===5);
 check("double save rejected",fails(()=>saveTimer(c,saved,[],full,f,100)));
 check("next day still unknown",saved.logs[0].recovery==="unknown");
 check("interrupt flag prevents progression",!success({...saved.logs[0],timingInterrupted:true,recovery:"normal"}));
 let interrupted=complete(t);
 check("resume full but timing interrupted",timerResult(interrupted,f).timingInterrupted&&timerResult(interrupted,f).status==="full");
 let short=timerAdvance(finishPhase(makeTimer(ticket)));short=timerStart(short,clock);clock+=1000;short=timerTick(short,clock);short=timerEnd(short,"fatigue",true);
 check("early stop offers cooldown",short.state==="ready"&&timerPhase(short).type==="cool"&&short.early);
 short=timerAdvance(finishPhase(short));const lr=timerResult(short,f);
 check("partial work plus cool recorded",lr.status==="shortened"&&lr.actual[1].seconds===1&&lr.actual[2].earlyCooldown===true);
 check("early cooldown validates",observed(ticket.dose,lr.actual,"shortened"));
 check("early cooldown never full",!observed(ticket.dose,lr.actual,"full"));
 check("early cooldown actual totals",actualTotals(saveTimer(c,s,[],short,f,100).logs[0]).total===601);
 const red=timerEnd(makeTimer(ticket),"symptoms",true);
 check("symptom stop no forced cooldown",red.state==="finished"&&red.warning);
 let warning=saveTimer(c,s,[],red,{...f,warning:true},100);
 check("warning before exercise still preserved",warning.logs[0].status==="skipped"&&warning.logs[0].warning===true);
 check("warning blocks future workouts",scheduledVisit(c,warning,[],p,c.slots[1].id,103,1800).action==="medical-review");
 const pain=timerEnd(makeTimer(ticket),"pain",true);
 check("pain stop no cooldown",pain.state==="finished"&&pain.pain);
 const d=interval("bike","bridge30");const it={...ticket,dose:d};
 let r=timerAdvance(finishPhase(makeTimer(it)));r=timerAdvance(finishPhase(r));r=finishPhase(r);
 check("at recovery boundary waits",r.state==="awaiting"&&timerPhase(r).type==="recovery");
 r=timerExtend(r,30);check("rest extension paused explicitly",r.targetMs===120000&&r.state==="paused");
 check("second extension rejected",fails(()=>timerExtend(r,1)));
 r=timerAdvance(finishPhase(r));r=complete(r);
 const result=timerResult(r,{...f,effort:6});
 check("extra rest actually logged",result.recoveryExtended&&result.actual[2].seconds===120&&result.status==="full");
 check("extra rest prevents progression",!success({...result,dose:d,recovery:"normal"}));
 check("cannot extend work",fails(()=>timerExtend(makeTimer(it),30)));
 const swimTicket={...ticket,dose:swim()};
 check("swim timer unavailable",fails(()=>makeTimer(swimTicket)));
 check("manual requires confirmation",fails(()=>saveManual(c,s,[],ticket,{...f,confirmed:false},100)));
 const manual=saveManual(c,s,[],ticket,{...f,status:"full",actual:phases(ticket.dose),recoveryExtended:false},100);
 check("manual provenance",manual.logs[0].source==="manual");
 check("manual unknown recovery",manual.logs[0].recovery==="unknown");
 check("malformed actual rejected",fails(()=>saveManual(c,s,[],ticket,{...f,status:"full",actual:[{type:"warm",seconds:99999}],recoveryExtended:false},100)));
 check("invalid early jump rejected",!observed(ticket.dose,[{type:"warm",seconds:300},{type:"work",seconds:300},{type:"cool",seconds:300,earlyCooldown:true}],"shortened"));
 check("partial zero activity not completed",timerResult(timerEnd(makeTimer(ticket),"time"),f).status==="skipped");
 let last=makeTimer(it);while(last.index<phases(d).length-2){last=timerAdvance(finishPhase(last));}last=finishPhase(last);
 last=timerEnd(last,"time",true);check("completed final recovery uses regular cooldown",last.early===false&&timerPhase(last).type==="cool");
 last=timerAdvance(finishPhase(last));check("final recovery plus cooldown validates full",timerResult(last,{...f,effort:6}).status==="full"&&observed(d,last.actual,"full"));
 check("orphan cooldown rejected",!observed(ticket.dose,[{type:"cool",seconds:60,earlyCooldown:true}],"shortened"));
 let early=timerAdvance(finishPhase(makeTimer(ticket)));early=timerStart(early,clock);clock+=1000;early=timerTick(early,clock);early=timerEnd(early,"fatigue",true);early=timerEnd(early,"time");check("fatigue reason preserved after stopping cooldown",timerResult(early,f).reason==="fatigue");
 return out;
}

const results=timerTests();for(const n of results)console.log('PASS '+n);console.log(results.length+' timer checks passed');
