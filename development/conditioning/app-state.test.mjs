import { steady } from './engine.mjs';
import { APP_KEY, appNew, appCurrent, appValidate, appStart, appTimer, appSave, appRecovery, appOutside, appCalendarEdit, appNextCycle, appAcknowledge, appReport, appBackup, appRestore, appPersist, appLoad } from './app-state.mjs';

function appTests(){
 const out=[];const check=(n,b)=>{if(!b)throw Error(n);out.push(n)};const fails=f=>{try{f();return false}catch{return true}};
 const p={mode:"bike",goal:"B",setup:"bike1",restricted:false,vigorousSuitable:true,existingHard:false,recovery:"normal",comfortableMinutes:5};
 const base=appNew(100,[0,3],5),id=appCurrent(base).calendar.slots[0].id;
 let a=appStart(base,p,id,100,1800,"one").app;
 check("active ticket issued",a.active.ticket.dose.minutes===5);
 check("single active",fails(()=>appStart(a,p,id,100,1800,"two")));
 check("no schedule edits during active",fails(()=>appCalendarEdit(a,"move",id,101,100)));
 check("no outside edits during active",fails(()=>appOutside(a,{id:"game",day:100,activity:"game",minutes:30,intensity:"hard"},100)));
 a=appTimer(a,"start",100,0);a=appTimer(a,"tick",100,1000);
 const restored=appRestore(appBackup(a,100),100);
 check("reload interrupts running clock",restored.active.timer.state==="interrupted"&&restored.active.timer.elapsedMs===1000);
 check("reload preserves ticket",appEq(restored.active.ticket,a.active.ticket));
 check("malformed timer rejected",fails(()=>appRestore(JSON.stringify({...a,active:{...a.active,timer:{...a.active.timer,elapsedMs:99999999}}}),100)));
 check("forged prescription rejected",fails(()=>appRestore(JSON.stringify({...a,active:{...a.active,ticket:{...a.active.ticket,dose:steady("bike",45,4)}}}),100)));
 check("unknown version rejected",fails(()=>appRestore(JSON.stringify({...base,version:99}),100)));
 check("no cross-day timer restart",fails(()=>appTimer(restored,"start",101,0)));
 a=appTimer(restored,"end",101,0,{reason:"time",cooldown:true});
 check("old session no new cooldown",a.active.timer.state==="finished");
 a=appSave(a,{confirmed:true,effort:2,quality:true,warning:false,pain:false},101);
 check("saved on original day",a.active===null&&a.history.logs[0].day===100&&a.history.logs[0].status==="shortened");
 check("actual total not planned",appReport(a,100,101).byMode.bike.knownTotalSeconds===1);
 check("next-day recovery unknown",appReport(a,100,101).unknownRecovery===1);
 a=appRecovery(a,"one","normal",101);
 check("next day report updates",appReport(a,100,101).unknownRecovery===0);
 const second=appCurrent(a).calendar.slots.find(x=>x.day===103);
 a=appOutside(a,{id:"game",day:103,activity:"Basketball",minutes:45,intensity:"hard"},103);
 a=appCalendarEdit(a,"replace",second.id,"game",103);
 check("external replacement separate",appReport(a,100,103).primary.external===1&&appReport(a,100,103).primary.full===0);
 check("outside minutes separate",appReport(a,100,103).outsideKnownMinutes===45);
 check("future not missed",appReport(a,100,103).primary.upcoming===6);
 check("no early review",fails(()=>appAcknowledge(a,100,103)));
 check("no early rollover",fails(()=>appNextCycle(a,103,[0,3],null,103)));
 a=appNextCycle(a,128,[1,4],null,128);
 check("rollover keeps history",a.cycles.length===2&&a.history.logs.length===1);
 check("old attendance fixed",appReport(a,100,128).primary.missed===6);
 check("review not required for rollover",appReport(a,100,128).reviewedDay===null);
 a=appAcknowledge(a,100,128);
 check("review acknowledgment dated",appReport(a,100,128).reviewedDay===128);
 check("round trip",appEq(appRestore(appBackup(a,128),128),a));
 const m=new Map(),storage={getItem:k=>m.get(k)??null,setItem:(k,v)=>m.set(k,v)};
 check("save local adapter",appPersist(storage,base,100).ok);
 check("load local adapter",appEq(appLoad(storage,100).app,base));
 check("revision conflict",appPersist(storage,a,128,99).reason==="storage-conflict");
 check("revision correct",appPersist(storage,a,128,0).ok);
 check("storage failure explicit",appPersist({getItem(){throw Error("quota")}},base,100).reason==="storage-unavailable");
 check("corruption explicit",appLoad({getItem(){return "broken"}},100).ok===false);
 let swimApp=appStart(base,{...p,mode:"swim",setup:"pool",waterCompetent:true},id,100,1800,"sw").app;
 check("swim manual only",swimApp.active.method==="manual"&&swimApp.active.timer===null);
 swimApp=appSave(swimApp,{confirmed:true,status:"full",actual:{lengths:4,swimSeconds:null,restSeconds:null},effort:3,quality:true,warning:false,pain:false,recoveryExtended:false},100);
 const sr=appReport(swimApp,100,100).byMode.swim;
 check("unknown swim time distinct",sr.unknownTotalVisits===1&&sr.unknownWorkVisits===1&&sr.unknownRecoveryTimeVisits===1&&Object.values(sr.lengthsByPool)[0]===4);
 return out;
}

const results=appTests();for(const n of results)console.log('PASS '+n);console.log(results.length+' app checks passed');
