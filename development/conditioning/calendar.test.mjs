import { steady, phases } from './engine.mjs';
import { emptyState, addLog, updateRecovery, addExternal } from './workflow.mjs';
import { makeCycle, validateCycle, validateLinks, slotStatus, reschedule, replaceWithExternal, trainingView, scheduledVisit, saveScheduled, skipScheduled, cycleReview } from './calendar.mjs';

function calendarTests(){
 const results=[];const check=(n,b)=>{if(!b)throw Error(n);results.push(n)};const fails=f=>{try{f();return false}catch{return true}};
 const p={mode:"bike",goal:"B",setup:"bike1",restricted:false,vigorousSuitable:true,existingHard:false,recovery:"normal",hardOptIn:true,comfortableMinutes:5};
 const s0=emptyState(100),c=makeCycle(100,[0,3],5),id=c.slots[0].id;
 const entry=(d,day,id,over={})=>({id,day,dose:d,setup:"bike1",source:"prior",status:"full",actual:phases(d),effort:d.effort[1],quality:true,recovery:"normal",recoveryDay:day+1,warning:false,pain:false,recoveryExtended:false,...over});
 const actual=d=>({id:"visit1",source:"timer",status:"full",actual:phases(d),effort:d.effort[1],quality:true,recovery:"unknown",warning:false,pain:false,recoveryExtended:false});
 check("four weeks eight primary four optional",c.slots.filter(x=>x.kind==="primary").length===8&&c.slots.length===12);
 check("duplicate dates rejected",fails(()=>makeCycle(100,[0,0])));
 check("optional overlap rejected",fails(()=>makeCycle(100,[0,3],3)));
 check("future slot cannot start",scheduledVisit(c,s0,[],p,c.slots[1].id,100,1800).dose===null);
 const start=scheduledVisit(c,s0,[],p,id,100,1800);
 check("first beginner visit",start.dose.kind==="steady"&&start.dose.minutes===5);
 let s=saveScheduled(c,s0,[],p,id,100,1800,actual(start.dose));
 check("actual binds planned slot",s.logs[0].plannedId===id&&s.logs[0].recovery==="unknown");
 check("duplicate slot blocked",scheduledVisit(c,s,[],p,id,100,1800).dose===null);
 check("same day recovery rejected",fails(()=>updateRecovery(s,"visit1","normal",100)));
 s=updateRecovery(s,"visit1","normal",101);
 check("next-day update",s.logs[0].recoveryDay===101);
 const second=c.slots.find(x=>x.day===103);
 check("unprepared B second slot steady",scheduledVisit(c,s,[],p,second.id,103,1800).dose.slot==="steady2");
 check("missed slot not catchup",scheduledVisit(c,s0,[],p,id,101,1800).action==="missed-no-catchup");
 check("missed counted only after day",slotStatus(c,s0,[],101).find(x=>x.id===id).status==="missed");
 const moved=reschedule(c,s,[],second.id,104,101);
 check("future slot reschedules",moved.slots.find(x=>x.id===second.id).day===104);
 check("cannot reschedule completed",fails(()=>reschedule(c,s,[],id,102,101)));
 check("cannot move into next week",fails(()=>reschedule(c,s,[],second.id,107,101)));
 check("cannot overlap existing optional",fails(()=>reschedule(c,s,[],second.id,105,101)));
 const prior=steady("bike",15,2);
 let prepared=addLog(s0,entry(prior,95,"pre1"),100);prepared=addLog(prepared,entry(prior,97,"pre2"),100);
 const i=scheduledVisit(c,prepared,[],p,second.id,103,1800);
 check("prepared B second slot intervals",i.dose?.id==="bridge30");
 check("adjacent hard blocks interval",scheduledVisit(c,prepared,[],{...p,adjacentDemand:true},second.id,103,1800).dose===null);
 let ext=addExternal(prepared,{id:"game",day:103,activity:"Basketball",minutes:45,intensity:"hard"},103);
 check("external load blocks same day visit",scheduledVisit(c,ext,[],p,second.id,103,1800).dose===null);
 const reps=replaceWithExternal(c,ext,[],second.id,"game",103);
 check("external replacement distinct",cycleReview(c,ext,reps,103).primary.external===1&&cycleReview(c,ext,reps,103).primary.full===0);
 check("duplicate replacement rejected",fails(()=>replaceWithExternal(c,ext,reps,second.id,"game",103)));
 const opt=c.slots.find(x=>x.kind==="optional");
 check("optional easy only",scheduledVisit(c,prepared,[],p,opt.id,105,1800).dose.effort[1]===3);
 check("optional unknown recovery rests",scheduledVisit(c,prepared,[],{...p,recovery:"unknown"},opt.id,105,1800).dose===null);
 const one=makeCycle(100,[0]);const first=one.slots[0];
 check("one day starts steady",scheduledVisit(one,prepared,[],p,first.id,100,1800).dose.kind==="steady");
 let oneState=saveScheduled(one,prepared,[],p,first.id,100,1800,actual(scheduledVisit(one,prepared,[],p,first.id,100,1800).dose));oneState=updateRecovery(oneState,"visit1","normal",101);
 check("one day prepared alternates",scheduledVisit(one,oneState,[],p,one.slots[1].id,107,1800).dose?.kind==="interval");
 check("cycle review separates missed",cycleReview(c,s,[],104).primary.full===1&&cycleReview(c,s,[],104).primary.missed===1);
 check("review due after 28 days",cycleReview(c,s,[],128).reviewDue);
 check("skip distinct from completion",cycleReview(c,skipScheduled(c,s0,[],id,100),[],100).primary.skipped===1);
 check("premature recovery cannot save",fails(()=>saveScheduled(c,s0,[],p,id,100,1800,{...actual(start.dose),recovery:"normal",recoveryDay:101})));
 check("warning overrides due date",scheduledVisit(c,s0,[],{...p,warning:true},id,100,1800).action==="medical-review");
 check("severe warning first",scheduledVisit(c,s0,[],{...p,currentSevere:true,warning:true},id,100,1800).action==="emergency");
 check("time cap retained",scheduledVisit(c,prepared,[],p,second.id,103,600).dose===null);
 return results;
}

const results=calendarTests();for(const n of results)console.log('PASS '+n);console.log(results.length+' calendar checks passed');
